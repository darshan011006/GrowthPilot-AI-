"use client";

import Link from "next/link";
import { useState } from "react";
import { Bar, BarChart, CartesianGrid, Legend, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { useCan } from "@/components/auth";
import { Alert, Badge, Button, Card, Empty, Loading, PageHeader, Select, Stat, useAction, useApi } from "@/components/ui";
import { api } from "@/lib/api";
import { fmtNum, fmtPct, fmtRelative, titleCase } from "@/lib/format";
import type { Analytics, Campaign, Group } from "@/lib/types";

const C1 = "#2f5d46";
const C2 = "#b5643c";

const SOURCE: Record<string, { label: string; tone: "demo" | "ok" | "warn" | "neutral"; note: string }> = {
  synthetic: { label: "Synthetic demo data", tone: "demo", note: "Generated by the demo adapter. Shows how the workflow behaves, not how real customers respond." },
  real: { label: "Real account data", tone: "ok", note: "From connected-account APIs or numbers entered by hand." },
  mixed: { label: "Mixed real + synthetic", tone: "warn", note: "Don't compare these groups directly." },
  none: { label: "No data yet", tone: "neutral", note: "Publish posts and collect metrics." },
};

function GroupChart({ title, groups }: { title: string; groups: Group[] }) {
  if (!groups.length) return null;
  const rows = groups.map((g) => ({ name: titleCase(g.key), er: +(g.mean_engagement_rate * 100).toFixed(2), n: g.n }));
  const small = groups.some((g) => g.n < 3);
  return (
    <Card title={title} subtitle={small ? "Some groups have fewer than 3 posts; differences may be noise." : "Mean engagement rate by reach per group."}>
      <div className="h-56">
        <ResponsiveContainer width="100%" height="100%">
          <BarChart data={rows} margin={{ left: -10 }}>
            <CartesianGrid strokeDasharray="3 3" stroke="#8884" />
            <XAxis dataKey="name" fontSize={11} />
            <YAxis unit="%" fontSize={11} />
            <Tooltip formatter={(v, _n, p) => [`${v}% (n=${(p.payload as { n: number }).n})`, "Engagement rate"]} />
            <Bar dataKey="er" fill={C1} radius={[4, 4, 0, 0]} isAnimationActive={false} />
          </BarChart>
        </ResponsiveContainer>
      </div>
      <ul className="mt-2 flex flex-wrap gap-1.5 text-xs">{groups.map((g) => <li key={g.key}><Badge>{titleCase(g.key)}: n={g.n}</Badge></li>)}</ul>
    </Card>
  );
}

export default function AnalyticsPage() {
  const can = useCan();
  const [campaign, setCampaign] = useState("");
  const { data, loading, error, reload } = useApi<Analytics>(`/api/analytics${campaign ? `?campaign_id=${campaign}` : ""}`);
  const camps = useApi<Campaign[]>("/api/campaigns");
  const collect = useAction();
  if (loading && !data) return <Loading />;
  if (error) return <Alert tone="bad">{error}</Alert>;
  if (!data) return null;
  const src = SOURCE[data.data_source];
  const t = data.totals;

  return (
    <div>
      <PageHeader title="Analytics" subtitle="Only metrics from authorised sources, never invented. Raw observations are kept apart from derived rates, and missing values stay missing."
        actions={<>
          <Select aria-label="Campaign" value={campaign} onChange={(e) => setCampaign(e.target.value)} className="w-auto"><option value="">All campaigns</option>{camps.data?.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}</Select>
          {can.edit && <Button busy={collect.busy} onClick={async () => { await collect.run(() => api.post("/api/analytics/collect")); reload(); }}>Collect latest metrics</Button>}
        </>} />
      <div className="mb-4"><Alert tone={src.tone === "ok" ? "ok" : src.tone === "neutral" ? "info" : src.tone === "warn" ? "warn" : "demo"} title={src.label}>{src.note} {data.freshness && `Last collected ${fmtRelative(data.freshness)}.`}</Alert></div>
      {collect.error && <div className="mb-3"><Alert tone="bad">{collect.error}</Alert></div>}

      {data.with_metrics === 0 ? <Empty title="No metrics yet">Publish posts (demo publishing works without credentials), then collect metrics.</Empty> : (
        <>
          <div className="mb-5 grid grid-cols-2 gap-3 md:grid-cols-5">
            <Stat label="Posts with metrics" value={`${data.with_metrics}/${data.published}`} hint={data.missing_metrics ? `${data.missing_metrics} missing` : undefined} />
            <Stat label="Reach (sum)" value={fmtNum(t.reach)} />
            <Stat label="Interactions" value={fmtNum(t.interactions)} hint="likes + comments + shares + saves" />
            <Stat label="Saves" value={fmtNum(t.saves)} />
            <Stat label="Engagement rate" value={fmtPct(t.engagement_rate_by_reach)} hint="interactions ÷ reach" />
          </div>
          <div className="grid gap-5 lg:grid-cols-2">
            <GroupChart title="By content type" groups={data.by_content_type} />
            <GroupChart title="By content pillar" groups={data.by_pillar} />
            {data.daily.length > 1 && (
              <Card title="Over time" subtitle="Reach and interactions by publish date." className="lg:col-span-2">
                <div className="h-64">
                  <ResponsiveContainer width="100%" height="100%">
                    <LineChart data={data.daily} margin={{ left: -5 }}>
                      <CartesianGrid strokeDasharray="3 3" stroke="#8884" />
                      <XAxis dataKey="date" fontSize={11} />
                      <YAxis fontSize={11} />
                      <Tooltip />
                      <Legend />
                      <Line type="monotone" dataKey="reach" stroke={C1} strokeWidth={2} dot isAnimationActive={false} />
                      <Line type="monotone" dataKey="interactions" stroke={C2} strokeWidth={2} dot isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </div>
              </Card>
            )}
            {data.by_campaign.length > 1 && <GroupChart title="By campaign" groups={data.by_campaign} />}
          </div>
          <Card className="mt-5" title="Posts">
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead className="text-left text-xs uppercase tracking-wide text-muted"><tr><th className="py-1.5 pr-3">Post</th><th className="pr-3">Type</th><th className="pr-3">Pillar</th><th className="pr-3">Reach</th><th className="pr-3">Interactions</th><th className="pr-3">Saves</th><th className="pr-3">ER</th><th>Source</th></tr></thead>
                <tbody className="divide-y divide-line">
                  {data.items.map((i) => (
                    <tr key={i.id}>
                      <td className="py-1.5 pr-3"><Link href={`/content/${i.id}`} className="hover:underline">{i.title}</Link></td>
                      <td className="pr-3">{i.content_type}</td><td className="pr-3">{i.pillar}</td>
                      <td className="pr-3">{fmtNum(i.reach)}</td><td className="pr-3">{fmtNum(i.interactions)}</td><td className="pr-3">{fmtNum(i.saves)}</td>
                      <td className="pr-3 font-semibold">{fmtPct(i.engagement_rate)}</td>
                      <td><Badge tone={i.source === "synthetic" ? "demo" : "ok"}>{i.source}</Badge></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </Card>
        </>
      )}
      <Card className="mt-5" title="Metric definitions">
        <dl className="grid gap-2 text-sm md:grid-cols-2">
          {Object.entries(data.definitions).map(([k, d]) => (
            <div key={k}><dt className="font-semibold">{d.label} <Badge tone={d.kind === "derived" ? "warm" : "neutral"}>{d.kind}</Badge></dt><dd className="text-muted">{d.definition}</dd></div>
          ))}
        </dl>
      </Card>
    </div>
  );
}
